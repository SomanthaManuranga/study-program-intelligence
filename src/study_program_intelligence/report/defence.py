"""Defence Q&A (Step 56): the most likely examiner questions with short, traceable answers.

Run from the repository root (after report.build):

    python -m study_program_intelligence.report.defence [--pdf]

Source: docs/defence/qa.md, written like the report sections: numbers only as {{key}} placeholders from
reports/key_numbers.yaml ({{val:key}} for the plain value); the same typed-number check as the report
(allowed patterns from docs/report/report.yaml). Output: docs/defence_qa.md (committed, so it can be read on GitHub
and printed), optionally reports/final/defence_qa.pdf.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

from .draft import OUT_DIR, PLACEHOLDER, SRC, typed_numbers
from .key_numbers import load as load_numbers

REPO_ROOT = Path(__file__).resolve().parents[3]
SOURCE = REPO_ROOT / "docs" / "defence" / "qa.md"
OUT = REPO_ROOT / "docs" / "defence_qa.md"


def build() -> list[str]:
    allowed = yaml.safe_load((SRC / "report.yaml").read_text(encoding="utf-8")).get("allowed_numbers", [])
    raw = SOURCE.read_text(encoding="utf-8")
    problems = [f"typed number '{x}'" for x in typed_numbers(raw, allowed)]
    kn = load_numbers()

    def sub(m: re.Match) -> str:
        key = m.group(1)
        bare = key.startswith("val:")
        key = key.removeprefix("val:")
        if key not in kn:
            problems.append(f"unknown key number {key}")
            return m.group(0)
        return str(kn[key]["value"]) if bare else kn[key]["display"]

    text = PLACEHOLDER.sub(sub, re.sub(r"<!--.*?-->\n?", "", raw, flags=re.S))
    n_q = len(re.findall(r"^### Q\d+", text, flags=re.M))
    header = ("<!-- Generated by `python -m study_program_intelligence.report.defence` from docs/defence/qa.md; "
              "edit the source, not this file. -->\n")
    OUT.write_text(header + text, encoding="utf-8")
    print(f"Written: {OUT.relative_to(REPO_ROOT)} ({n_q} questions)")
    return problems


def main(argv: list[str] | None = None) -> None:
    argv = sys.argv[1:] if argv is None else argv
    problems = build()
    if problems:
        print("FAILED checks:\n  " + "\n  ".join(problems))
        sys.exit(1)
    if "--pdf" in argv:
        import pypandoc
        OUT_DIR.mkdir(parents=True, exist_ok=True)
        pdf = OUT_DIR / "defence_qa.pdf"
        pypandoc.convert_file(str(OUT), "pdf", outputfile=str(pdf),
                              extra_args=["--pdf-engine=xelatex", "-V", "geometry:margin=2.2cm", "-V", "fontsize=10pt"])
        print(f"Converted: {pdf.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
